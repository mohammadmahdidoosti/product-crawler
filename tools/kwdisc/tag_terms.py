"""Tags the second-pass terms (menu junk, services, brands, already in the missing list, already on the site, family,
adjacent) and writes the list that gets Google Suggest: family + adjacent terms.
In:  /data/runs/disc-full2/terms_v2.csv     Out: /data/runs/disc-full2/terms_tag.csv, /data/tmp/sug_terms.txt
Run in the app container: python tools/kwdisc/tag_terms.py"""
import csv, re, collections
csv.field_size_limit(10**9)
B=r'(?:^|\s)'; E=r'(?:\s|$)'
def W(*ws): return re.compile(B+'(?:'+'|'.join(ws)+')'+E)
JUNKW=W('مقالات?','مقاله','ارتباط','پروژه(?: ?ها)?','آموزش','آموزشی ما','راهنمای خرید','راهنمای انتخاب','مقایسه','پس از فروش','نقشه سایت','علاقه ?مندی(?: ?ها)?','نمونه ?کار(?: ?ها)?','دانشنامه','اخبار','رویدادها?','تخفیف(?: ?ها)?','جشنواره','درباره(?: ما)?','افتخارات','گواهینامه(?: ?ها)?','مجوزها?','سوالات','پرسش(?: ?ها)?','تماس','پشتیبانی','شعب','همکاری','استخدام','فرصت(?: ?های)? شغلی','ضمانت','بازگشت کالا','حریم خصوصی','قوانین','معرفی','وبینار','کاتالوگ','تصاویر','گالری','مجله','وبلاگ','بلاگ','نظرات','دانلود','ورود','خروج','حساب کاربری','سبد خرید','منو','بررسی کامل','صفحه اصلی','صفحه نخست','صفحه ی اصلی','مشاهده(?: همه)?','همه محصولات','تمامی','پلن','عضویت','ثبت ?نام','پیگیری','فرمولاسیون','شرکت','کارخانه','سایت','اپلیکیشن','نشریه','چشم ?انداز','اهداف','تاریخچه','تاریخ ما','خدمات ما','ما','پیشنهاد(?: ما)?','جدیدترین','پرفروش(?: ?ترین)?','محبوب(?: ?ترین)?','ویژه','حراج','دسته ?بندی','زیر ?دسته','سایر','بیشتر','لیست قیمت','لیست','قیمت روز','استعلام',r'navigate_\w+','در (?:تهران|مشهد|اصفهان|شیراز|تبریز|کرج)','برای شرکت')
START=re.compile(r'^(?:و |در |از |با |به |برای |چرا |چطور |چگونه |آیا )')
SOLO=re.compile(r'^(?:همه|کالا|محصولات?|خانه|فروشگاه|خرید|فروش|قیمت|عمده|صفحه|ایران|تهران|سفید|مشکی|طوسی|قرمز|آبی|سبز|زرد|نارنجی|بنفش|صورتی|قهوه ای|کرم|طلایی|نقره ای|بزرگ|کوچک|متوسط|جدید|اورجینال)$')
SVC=re.compile(r'^(?:تعمیرات|تعمیر(?:گاه)?|کلینیک|اجاره|خدمات|نرم ?افزار|طراحی|نصب|مشاوره|حمل|باربری|سمپاشی|حذف|کالیبراسیون|بازرسی|شستشو|نظافت|اجرای|اجرا|ساخت|برش|چاپ|تراش|ریخته ?گری|آبکاری|رنگ ?آمیزی|سفارش)\b')
BRAND=W('سامسونگ','شیائومی','اپل','هواوی','نوکیا','ال ?جی','سونی','سوزوکی','هیوندای','کیا','تویوتا','نیسان','بنز','بی ?ام ?و','رنو','پژو','پراید','سایپا','ایران ?خودرو','تیبا','دنا','سمند','هوندا','یاماها','KTM','ماکیتا','متابو','رونیکس','توسن','دیوالت','میلواکی')

D = "/data/runs/disc-full2"
T = list(csv.DictReader(open(D + "/terms_v2.csv", encoding="utf-8")))
C = collections.Counter()
with open(D + "/terms_tag.csv", "w", encoding="utf-8", newline="") as fh, open("/data/tmp/sug_terms.txt", "w", encoding="utf-8") as sf:
    w = csv.writer(fh)
    w.writerow(["term", "tag", "n_keywords", "mentions", "keyword_ids"])
    for t in T:
        x = t["term"]
        if JUNKW.search(x) or START.search(x) or SOLO.search(x) or re.search(r"[A-Za-z]{3,}.*\(|_", x): tag = "آشغال منو"
        elif SVC.search(x): tag = "خدمات"
        elif t["in_missing_list"] == "1": tag = "خودش در لیست نداریم"
        elif t["on_site"]: tag = "داریم (" + t["on_site"] + ")"
        elif BRAND.search(x): tag = "برند/مدل"
        else: tag = t["type"]
        C[tag] += 1
        w.writerow([x, tag, t["n_keywords"], t["mentions"], t["keyword_ids"]])
        if tag in ("هم‌خانواده", "هم‌جوار"):
            sf.write(x + "\n")
print(dict(C), flush=True)
