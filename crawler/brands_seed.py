def rows():
    seen = set()
    for origin, block in (("iranian", IRANIAN), ("foreign", FOREIGN), ("unknown", UNKNOWN)):
        for b in block.replace("\n", "").split("|"):
            b = b.strip()
            if b and b not in seen:
                seen.add(b)
                yield {"brand": b, "origin": origin}
